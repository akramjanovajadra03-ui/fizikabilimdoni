let selectedLevel = "easy";
let questions = [];
let currentIndex = 0;
let correctAnswers = 0;
let wrongAnswers = 0;
let userAnswers = [];
let timer = null;
let timeLeft = 20;
let answered = false;
let studentName = "";

const startScreen = document.getElementById("startScreen");
const quizScreen = document.getElementById("quizScreen");
const resultScreen = document.getElementById("resultScreen");

document.querySelectorAll(".level").forEach(button => {
  button.addEventListener("click", () => {
    document.querySelectorAll(".level").forEach(item => {
      item.classList.remove("active");
    });

    button.classList.add("active");
    selectedLevel = button.dataset.level;
  });
});

document.getElementById("startBtn").addEventListener("click", startTest);

function startTest() {
  studentName = document.getElementById("studentName").value.trim();

  if (!studentName) {
    alert("Iltimos, ism va familiyangizni kiriting!");
    return;
  }

  questions = shuffle([...questionsBank[selectedLevel]]).slice(0, 10);

  currentIndex = 0;
  correctAnswers = 0;
  wrongAnswers = 0;
  userAnswers = [];

  startScreen.classList.add("hidden");
  resultScreen.classList.add("hidden");
  quizScreen.classList.remove("hidden");

  showQuestion();
}

function shuffle(array) {
  for (let i = array.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [array[i], array[j]] = [array[j], array[i]];
  }
  return array;
}

function showQuestion() {
  clearInterval(timer);

  answered = false;
  timeLeft = 20;

  const question = questions[currentIndex];

  document.getElementById("questionNumber").textContent =
    `${currentIndex + 1} / ${questions.length}`;

  document.getElementById("questionText").textContent = question[0];
  document.getElementById("timer").textContent = timeLeft;

  document.getElementById("progressBar").style.width =
    `${(currentIndex / questions.length) * 100}%`;

  document.getElementById("feedback").textContent = "";
  document.getElementById("answers").innerHTML = "";

  question[1].forEach((answer, index) => {
    const button = document.createElement("button");
    button.className = "answer-btn";
    button.textContent = `${String.fromCharCode(65 + index)}. ${answer}`;

    button.addEventListener("click", () => selectAnswer(index));

    document.getElementById("answers").appendChild(button);
  });

  timer = setInterval(() => {
    timeLeft--;
    document.getElementById("timer").textContent = timeLeft;

    if (timeLeft <= 0) {
      clearInterval(timer);
      selectAnswer(null);
    }
  }, 1000);
}

function selectAnswer(selectedIndex) {
  if (answered) return;

  answered = true;
  clearInterval(timer);

  const question = questions[currentIndex];
  const correctIndex = question[2];
  const isCorrect = selectedIndex === correctIndex;

  if (isCorrect) {
    correctAnswers++;
  } else {
    wrongAnswers++;
  }

  userAnswers.push({
    question: question[0],
    selected: selectedIndex === null
      ? "Vaqt tugadi — javob berilmadi"
      : question[1][selectedIndex],
    correct: question[1][correctIndex],
    isCorrect: isCorrect
  });

  const buttons = document.querySelectorAll(".answer-btn");

  buttons.forEach((button, index) => {
    button.disabled = true;

    if (index === correctIndex) {
      button.classList.add("correct");
    }

    if (selectedIndex === index && !isCorrect) {
      button.classList.add("wrong");
    }
  });

  const feedback = document.getElementById("feedback");

  if (isCorrect) {
    feedback.textContent = "✓ To‘g‘ri javob!";
    feedback.style.color = "#25d366";
  } else {
    feedback.textContent = selectedIndex === null
      ? "Vaqt tugadi!"
      : "✗ Noto‘g‘ri javob!";
    feedback.style.color = "#ff6666";
  }

  setTimeout(() => {
    currentIndex++;

    if (currentIndex < questions.length) {
      showQuestion();
    } else {
      showResult();
    }
  }, 1100);
}

function showResult() {
  clearInterval(timer);

  quizScreen.classList.add("hidden");
  resultScreen.classList.remove("hidden");

  const score = correctAnswers * 10;

  document.getElementById("studentResult").textContent =
    `O‘quvchi: ${studentName}`;

  document.getElementById("score").textContent = score;
  document.getElementById("correctCount").textContent = correctAnswers;
  document.getElementById("wrongCount").textContent = wrongAnswers;

  const levels = {
    easy: "Oson",
    medium: "O‘rta",
    hard: "Qiyin"
  };

  document.getElementById("levelResult").textContent =
    `Tanlangan daraja: ${levels[selectedLevel]}`;

  const review = document.getElementById("answerReview");
  review.innerHTML = "";

  userAnswers.forEach((answer, index) => {
    const item = document.createElement("div");

    item.className = `review-item ${answer.isCorrect ? "right" : "wrong"}`;

    const question = document.createElement("p");
    question.className = "review-question";
    question.textContent = `${index + 1}. ${answer.question}`;

    const yourAnswer = document.createElement("p");
    yourAnswer.className = "your-answer";
    yourAnswer.textContent = `Sizning javobingiz: ${answer.selected}`;

    if (answer.isCorrect) {
      yourAnswer.classList.add("correct-text");
    }

    const correctAnswer = document.createElement("p");
    correctAnswer.className = "correct-answer";
    correctAnswer.textContent = `To‘g‘ri javob: ${answer.correct}`;

    item.append(question, yourAnswer, correctAnswer);
    review.appendChild(item);
  });

  document.getElementById("progressBar").style.width = "100%";
}
